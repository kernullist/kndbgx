const CommandSpec *FindCommand(const std::wstring &name)
{
    // Keep the legacy spelling parseable without advertising it in the command list.
    const wchar_t *lookup = _wcsicmp(name.c_str(), L"contract") == 0 ? L"command-schema" : name.c_str();
    for (const auto &spec : CommandSpecs())
    {
        if (_wcsicmp(lookup, spec.Name) == 0)
        {
            return &spec;
        }
        for (const auto *alias : spec.Aliases)
        {
            if (_wcsicmp(lookup, alias) == 0)
            {
                return &spec;
            }
        }
    }
    return nullptr;
}

const wchar_t *SupportName(SupportLevel support)
{
    switch (support)
    {
    case SupportLevel::Stable:
        return L"Stable";
    case SupportLevel::Experimental:
        return L"Experimental";
    default:
        return L"Unsupported";
    }
}

TargetMode EffectiveTargetModes(const CommandSpec &spec)
{
    if (spec.Modes != TargetMode::Any)
    {
        return spec.Modes;
    }
    if (spec.Requires == Capability::None || spec.Requires == Capability::Engine)
    {
        return TargetMode::Any;
    }
    return TargetMode::DumpAndLive;
}

const wchar_t *TargetModeName(TargetMode modes)
{
    switch (modes)
    {
    case TargetMode::KernelDump:
        return L"KernelDump";
    case TargetMode::LiveKernel:
        return L"LiveKernel";
    case TargetMode::DumpAndLive:
        return L"DumpAndLive";
    default:
        return L"Any";
    }
}

std::wstring TargetModeDisplayName(const CommandSpec &spec)
{
    if (spec.Requires == Capability::LocalKernelX64 && EffectiveTargetModes(spec) == TargetMode::LiveKernel)
    {
        return L"LiveKernelLocal";
    }
    return TargetModeName(EffectiveTargetModes(spec));
}

bool ParseCommand(const std::wstring &line, ParsedCommand *parsed)
{
    if (parsed == nullptr)
    {
        return false;
    }
    *parsed = {};
    const auto input = knutil::Trim(line);
    if (input.empty() || !knutil::Tokenize(input, &parsed->Arguments, &parsed->Error, &parsed->Quoted))
    {
        parsed->Error = L"InvalidInput: malformed command";
        return false;
    }
    const auto end = input.find_first_of(L" \t");
    parsed->RawArguments = end == std::wstring::npos ? L"" : knutil::Trim(input.substr(end));
    if (input[0] == L'?')
    {
        parsed->Arguments = {L"?", knutil::Trim(input.substr(1))};
        parsed->Quoted = {false, false};
        parsed->RawArguments = parsed->Arguments[1];
    }
    parsed->Spec = FindCommand(parsed->Arguments[0]);
    if (parsed->Spec == nullptr)
    {
        parsed->Error = L"Unsupported: unknown command; use explicit raw mode for host commands";
        return false;
    }
    parsed->Arguments[0] = parsed->Spec->Name;
    if (std::wstring(parsed->Spec->Name) != L"raw" && std::wstring(parsed->Spec->Name) != L"submit")
    {
        // Quoted filesystem names may contain a semicolon; expressions are checked separately.
        bool quoted = false;
        size_t backslashes = 0;
        for (const auto ch : input)
        {
            if (ch == L'"' && backslashes % 2 == 0)
            {
                quoted = !quoted;
            }
            if (!quoted && (ch == L';' || ch == L'{' || ch == L'}'))
            {
                parsed->Error = L"InvalidInput: compound commands require explicit raw mode";
                return false;
            }
            backslashes = ch == L'\\' ? backslashes + 1 : 0;
        }
    }
    size_t positional = 0;
    std::set<std::wstring> options;
    for (size_t i = 1; i < parsed->Arguments.size(); ++i)
    {
        const auto &argument = parsed->Arguments[i];
        if (argument.empty())
        {
            parsed->Error = L"InvalidInput: empty argument";
            return false;
        }
        if (argument[0] == L'/' && !parsed->Quoted[i] && std::wstring(parsed->Spec->Name) != L"raw" &&
            std::wstring(parsed->Spec->Name) != L"plan" && std::wstring(parsed->Spec->Name) != L"submit")
        {
            const OptionSpec *matched = nullptr;
            for (const auto &option : parsed->Spec->Options)
            {
                if (_wcsicmp(argument.c_str(), option.Name) == 0)
                {
                    matched = &option;
                    break;
                }
            }
            if (matched == nullptr || !options.insert(matched->Name).second ||
                (matched->TakesValue && (i + 1 == parsed->Arguments.size() || parsed->Arguments[i + 1].empty())))
            {
                parsed->Error = L"InvalidInput: unknown, duplicate or incomplete option";
                return false;
            }
            if (matched->TakesValue)
            {
                ++i;
            }
        }
        else
        {
            ++positional;
            parsed->Positionals.push_back(argument);
        }
    }
    if (positional < parsed->Spec->MinArguments || positional > parsed->Spec->MaxArguments)
    {
        parsed->Error = L"InvalidInput: usage: " + std::wstring(parsed->Spec->Grammar);
        return false;
    }
    return true;
}

bool ParseUiCommand(const std::wstring &line, ParsedCommand *parsed)
{
    if (parsed == nullptr)
    {
        return false;
    }
    *parsed = {};
    const auto input = knutil::Trim(line);
    if (input.empty() || line.size() > 32768 || line.find_first_of(L"\r\n") != std::wstring::npos || line.find(L'\0') != std::wstring::npos)
    {
        parsed->Error = L"InvalidInput: malformed command";
        return false;
    }
    // Resolve the command name before parsing arguments: a malformed registered
    // command must not fall through to the engine. WinDbg owns all other grammar.
    const auto name = input.substr(0, input.find_first_of(L" \t\v\f;{}"));
    const auto tokens = knutil::Tokenize(name);
    const bool expression = input[0] == L'?' && (input.size() == 1 || input[1] != L'?');
    if (expression || FindCommand(name) != nullptr || (tokens.size() == 1 && FindCommand(tokens[0]) != nullptr))
    {
        return ParseCommand(line, parsed);
    }
    static const CommandSpec host =
    {
        L"windbg", {}, L"Debugger", L"Forward UI input to WinDbg", L"<WinDbg command>",
        Effect::OpaqueEngine, Capability::Engine, SupportLevel::Stable, 0, 0, {}, WinDbgCommand
    };
    parsed->Spec = &host;
    parsed->Arguments = {host.Name};
    parsed->RawArguments = line;
    return true;
}

knjson::Value CommandContract()
{
    auto rows = knjson::Value::MakeArray();
    for (const auto &spec : CommandSpecs())
    {
        auto row = knjson::Value::MakeObject();
        row.Set(L"name", knjson::Value(spec.Name));
        row.Set(L"group", knjson::Value(spec.Group));
        row.Set(L"summary", knjson::Value(spec.Synopsis));
        row.Set(L"grammar", knjson::Value(spec.Grammar));
        row.Set(L"support", knjson::Value(SupportName(spec.Support)));
        const wchar_t *capability = spec.Requires == Capability::None            ? L"None"
                                    : spec.Requires == Capability::Engine        ? L"Engine"
                                    : spec.Requires == Capability::Target        ? L"Target"
                                    : spec.Requires == Capability::StoppedTarget ? L"StoppedTarget"
                                    : spec.Requires == Capability::KernelX64     ? L"KernelX64"
                                                                                 : L"LocalKernelX64";
        row.Set(L"capability", knjson::Value(capability));
        row.Set(L"targetModes", knjson::Value(TargetModeDisplayName(spec)));
        row.Set(L"effectMask", knjson::Value(static_cast<double>(static_cast<unsigned>(spec.Effects))));
        auto aliases = knjson::Value::MakeArray();
        for (const auto *alias : spec.Aliases)
        {
            aliases.Push(knjson::Value(alias));
        }
        row.Set(L"aliases", aliases);
        auto options = knjson::Value::MakeArray();
        for (const auto &option : spec.Options)
        {
            auto value = knjson::Value::MakeObject();
            value.Set(L"name", knjson::Value(option.Name));
            value.Set(L"takesValue", knjson::Value(option.TakesValue));
            options.Push(value);
        }
        row.Set(L"options", options);
        rows.Push(row);
    }
    return rows;
}
