def digest(data):
    return hashlib.sha256(data).hexdigest()


class PE:
    def __init__(self, path):
        self.data = pathlib.Path(path).read_bytes()
        self.nt = self.unpack("I", 60)[0]
        if self.data[:2] != b"MZ" or self.data[self.nt:self.nt + 4] != b"PE\0\0":
            raise ValueError("Invalid PE")
        self.machine, count, self.timestamp, _, _, size, _ = self.unpack("HHIIIHH", self.nt + 4)
        self.optional = self.nt + 24
        if self.unpack("H", self.optional)[0] != 0x20B or count > 96 or size < 112:
            raise ValueError("Expected bounded PE32+ image")
        self.sections = []
        for index in range(count):
            start = self.optional + size + index * 40
            name = self.data[start:start + 8].rstrip(b"\0").decode("ascii")
            virtual_size, address, raw_size, offset = self.unpack("IIII", start + 8)
            flags = self.unpack("I", start + 36)[0]
            self.sections.append((name, address, virtual_size, offset, raw_size, flags))

    def unpack(self, fmt, offset):
        if offset < 0 or offset + struct.calcsize("<" + fmt) > len(self.data):
            raise ValueError("PE boundary")
        return struct.unpack_from("<" + fmt, self.data, offset)

    def offset(self, rva, size):
        matches = [raw + rva - va for _, va, _, raw, length, _ in self.sections if va <= rva and rva - va + size <= length]
        if len(matches) != 1 or matches[0] + size > len(self.data):
            raise ValueError("Ambiguous/unmapped RVA")
        return matches[0]

    def directory(self, index):
        return self.unpack("II", self.optional + 112 + 8 * index)

    def inspect(self):
        flags = self.unpack("H", self.optional + 70)[0]
        load_rva, load_size = self.directory(10)
        load = self.offset(load_rva, min(load_size, 280))
        load_length = self.unpack("I", load)[0]
        if min(load_length, load_size) < 148:
            raise ValueError("Load configuration missing CFG fields")
        guard_flags = self.unpack("I", load + 144)[0]
        cfg_count = self.unpack("Q", load + 136)[0]
        cookie = self.unpack("Q", load + 88)[0]
        eh_count = self.unpack("Q", load + 272)[0] if min(load_length, load_size) >= 280 else 0
        debug_rva, debug_size = self.directory(6)
        debug = self.offset(debug_rva, debug_size)
        cv = None
        cet = False
        reproducible = False
        for entry in range(debug, debug + debug_size, 28):
            kind, length, _, raw = self.unpack("IIII", entry + 12)
            if raw + length > len(self.data):
                raise ValueError("Debug record outside file")
            if kind == 2 and self.data[raw:raw + 4] == b"RSDS" and length >= 24:
                require_pdb_basename(self.data[raw + 24:raw + length])
                cv = {"guid": str(uuid.UUID(bytes_le=self.data[raw + 4:raw + 20])), "age": self.unpack("I", raw + 20)[0]}
            if kind == 20 and length >= 2:
                cet = bool(self.unpack("H", raw)[0] & 1)
            reproducible = reproducible or kind == 16
        if not cv:
            raise ValueError("Release PDB identity missing")
        return {
            "machine": hex(self.machine), "aslr": bool(flags & 0x40), "nx": bool(flags & 0x100),
            "highEntropyVa": bool(flags & 0x20), "cfg": bool(flags & 0x4000 and guard_flags & 0x100 and cfg_count),
            "cfgFunctionCount": cfg_count, "securityCookie": bool(cookie), "cetCompatible": cet,
            "ehContinuationCount": eh_count, "reproducibleDebugEntry": reproducible, "pdb": cv,
        }


