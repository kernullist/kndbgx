def publication_terms(path=None):
    policy = path if path is not None else ROOT / ".publication-terms.local.json"
    try:
        checkout = ROOT.resolve()
        candidates = (policy.absolute(), policy.resolve())
    except (OSError, RuntimeError, ValueError):
        raise ValueError("Private term policy path could not be resolved") from None
    for candidate in candidates:
        if candidate.is_relative_to(checkout) and not private_path(candidate.relative_to(checkout).as_posix()):
            raise ValueError("Private term policy must use a local-only path")
    return load_private_terms(policy, optional=path is None)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("docs", "check-docs", "inspect", "package", "check-deps", "check-artifacts", "check-rebuilds", "check-privacy"))
    parser.add_argument("--configuration", default="Release", choices=("Debug", "Release"))
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "artifacts" / f"KNDbgX-{VERSION}-Windows-x64.zip")
    parser.add_argument("--first-directory", type=pathlib.Path)
    parser.add_argument("--private-terms-file", type=pathlib.Path,
                        help="Local-only terms for check-privacy or package; defaults to .publication-terms.local.json when present")
    args = parser.parse_args()
    if args.private_terms_file is not None and args.mode not in ("check-privacy", "package"):
        parser.error("--private-terms-file applies only to check-privacy and package")
    private_patterns = ()
    if args.mode in ("check-privacy", "package"):
        private_patterns = publication_terms(args.private_terms_file)
    if args.mode in ("docs", "check-docs"):
        generated_docs(args.configuration, args.mode == "check-docs")
        print("Command documents verified")
    elif args.mode == "check-deps":
        print("Dependency files verified:", len(dependencies()["files"]))
    elif args.mode == "check-privacy":
        print("PASS release.publication-privacy files:", check_repository(ROOT, private_patterns),
              "private term rules:", len(private_patterns))
    elif args.mode == "inspect":
        print(json.dumps(PE(ROOT / "x64" / args.configuration / "kndbgx.dll").inspect(), indent=2))
    elif args.mode == "check-artifacts":
        check_artifacts(args.configuration)
    elif args.mode == "check-rebuilds":
        if args.first_directory is None:
            parser.error("check-rebuilds requires --first-directory")
        check_rebuilds(args.configuration, args.first_directory)
    else:
        package(args.configuration, args.output, private_patterns)


if __name__ == "__main__":
    main()
