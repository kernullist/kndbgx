def verify_dependency(content, entry):
    if digest(content) != entry["sha256"]:
        # Git autocrlf may normalize tracked text on another checkout.
        if entry["verification"] != "line-endings-only" or digest(content.replace(b"\r\n", b"\n")) != entry.get("normalizedSha256"):
            raise ValueError("Dependency hash mismatch: " + entry["path"])


def dependencies():
    lock = json.loads((ROOT / "deps/dependencies.lock.json").read_text(encoding="utf-8"))
    for entry in lock["files"]:
        content = (ROOT / entry["path"]).read_bytes()
        verify_dependency(content, entry)
    return lock


def binary_evidence(configuration, binary=None):
    binary = binary or ROOT / "x64" / configuration / "kndbgx.dll"
    pdb = binary.with_suffix(".pdb")
    info = PE(binary).inspect()
    for required in ("aslr", "nx", "highEntropyVa", "cfg", "securityCookie", "cetCompatible", "reproducibleDebugEntry"):
        if not info[required]:
            raise ValueError("Binary hardening/reproducibility gate failed: " + required)
    if info["machine"] != "0x8664" or not info["ehContinuationCount"]:
        raise ValueError("x64 EH continuation metadata required")
    evidence = json.loads(run(ROOT / "x64" / configuration / "kndbgx-engine-test.exe", "--pdb-type", pdb, info["pdb"]["guid"], info["pdb"]["age"], "@kndbgx"))
    if not (evidence.get("present") or evidence.get("publicPresent")):
        raise ValueError("Release PDB lacks the extension entrypoint")
    return info


def check_rebuilds(configuration, first_directory):
    if configuration != "Release":
        raise ValueError("Rebuild comparison requires Release artifacts")
    first = first_directory.resolve() / "first-kndbgx.dll"
    second = ROOT / "x64" / configuration / "kndbgx.dll"
    hashes = [{"dll": digest(path.read_bytes()), "pdb": digest(path.with_suffix(".pdb").read_bytes())}
              for path in (first, second)]
    if hashes[0]["dll"] != hashes[1]["dll"]:
        raise ValueError("Clean Release DLLs differ")
    identities = [binary_evidence(configuration, path)["pdb"] for path in (first, second)]
    if identities[0] != identities[1]:
        raise ValueError("Clean Release symbol identities differ")
    evidence = {"schema": "kndbgx.rebuild.v1", "first": hashes[0], "second": hashes[1],
                "dllByteIdentical": True, "pdbByteIdentical": hashes[0]["pdb"] == hashes[1]["pdb"],
                "bothPdbIdentitiesAndEntrypointsVerified": True, "pdbIdentity": identities[0],
                "scope": "Same checkout, compiler, SDK and absolute path; clean solution versus clean direct-project build. "
                         "DLL bytes are required to match. Raw MSVC PDB byte determinism is not claimed; each matching PDB is retained."}
    (first_directory / "reproducible-build.json").write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(evidence, indent=2))
    print("PASS release.reproducible-release-dll")
    print("PASS release.both-release-pdbs-match")


def check_artifacts(configuration):
    lock = dependencies()
    for entry in lock["files"]:
        content = (ROOT / entry["path"]).read_bytes()
        try:
            verify_dependency(content + b"tamper", entry)
        except ValueError:
            continue
        raise ValueError("Dependency tamper negative control failed: " + entry["path"])
    print("PASS release.dependency-hash-tamper-rejected")
    print(json.dumps(binary_evidence(configuration), indent=2))
    print("PASS release.binary-hardening-and-pdb")


def source_manifest(private_patterns=()):
    sources = {}
    for name in git_names(ROOT):
        if pathlib.PurePosixPath(name).name.lower() in ("agents.md", "agents.override.md"):
            continue
        require_public(name, None, ROOT, private_patterns)
        if not (ROOT / name).exists():
            continue
        content = read_public_file(ROOT, name)
        require_public(name, content, ROOT, private_patterns)
        sources[name] = digest(content)
    return sources


